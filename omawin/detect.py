"""Detect how apps open, and write Hyprland launch rules."""

from __future__ import annotations

import json
import os
import re
import subprocess
from pathlib import Path

HOME = Path.home()
CONFIG_DIR = HOME / ".config" / "omawin"
RULES_JSON = CONFIG_DIR / "rules.json"
RULES_LUA = HOME / ".config" / "hypr" / "omawin-rules.lua"
DEFAULT_APPS = Path("/usr/share/omarchy/default/hypr/apps")
USER_HYPR = HOME / ".config" / "hypr"

MODES = ("default", "tiled", "float", "center", "fullscreen")

MODE_LABELS = {
    "default": "Default",
    "tiled": "Tiled",
    "float": "Float",
    "center": "Center",
    "fullscreen": "Full",
}

WINDOW_CALL = re.compile(
    r"""o\.window\(\s*(?:"([^"]+)"|'([^']+)'|\{\s*class\s*=\s*"([^"]+)")""",
    re.MULTILINE,
)
STEAM_GAME = re.compile(r"steam://rungameid/(\d+)|steam\s+steam://.*?(?:/(\d+))", re.I)
STEAM_CLIENT_IDS = {"steam.desktop", "steam_steam.desktop"}


def load_overrides() -> dict[str, dict]:
    if not RULES_JSON.is_file():
        return {}
    try:
        data = json.loads(RULES_JSON.read_text())
    except (OSError, json.JSONDecodeError):
        return {}
    rules = data.get("rules") if isinstance(data, dict) else data
    return rules if isinstance(rules, dict) else {}


def save_overrides(rules: dict[str, dict]) -> None:
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)
    RULES_JSON.write_text(json.dumps({"rules": rules}, indent=2) + "\n")
    RULES_LUA.parent.mkdir(parents=True, exist_ok=True)
    RULES_LUA.write_text(render_lua(rules))


def render_lua(rules: dict[str, dict]) -> str:
    lines = [
        "-- Generated by omawin. Do not edit.",
        "",
    ]
    for _app_id, rule in sorted(rules.items(), key=lambda item: item[0].lower()):
        wm_class = (rule.get("class") or "").strip()
        mode = rule.get("mode") or "default"
        if not wm_class or mode == "default":
            continue
        body = lua_body(mode)
        if not body:
            continue
        lines.append(f'o.window("{lua_escape(wm_class)}", {{ {body} }})')
    lines.append("")
    return "\n".join(lines)


def lua_body(mode: str) -> str:
    if mode == "tiled":
        return "float = false"
    if mode == "float":
        return "float = true"
    if mode == "center":
        return "float = true, center = true"
    if mode == "fullscreen":
        return "fullscreen = true"
    return ""


def lua_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def reload_hyprland() -> None:
    subprocess.run(["hyprctl", "reload"], check=False, capture_output=True)


def live_clients() -> list[dict]:
    try:
        raw = subprocess.check_output(["hyprctl", "-j", "clients"], text=True)
        data = json.loads(raw)
    except (OSError, subprocess.CalledProcessError, json.JSONDecodeError):
        return []
    return data if isinstance(data, list) else []


def live_mode_for_class(wm_class: str, clients: list[dict] | None = None) -> str | None:
    if not wm_class:
        return None
    needle = wm_class.lower()
    clients = live_clients() if clients is None else clients
    modes = []
    for client in clients:
        cls = str(client.get("class") or client.get("initialClass") or "").lower()
        if cls != needle:
            continue
        if int(client.get("fullscreen") or 0):
            modes.append("fullscreen")
        elif client.get("floating"):
            modes.append("float")
        else:
            modes.append("tiled")
    if not modes:
        return None
    # Prefer the most common live state.
    return max(set(modes), key=modes.count)


def first_lua_table(text: str) -> str:
    start = text.find("{")
    if start < 0:
        return ""
    depth = 0
    for index, char in enumerate(text[start:], start):
        if char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return text[start : index + 1]
    return ""


def infer_mode_from_props(props: str) -> str | None:
    text = props.lower()
    if re.search(r"fullscreen\s*=\s*true", text):
        return "fullscreen"
    if re.search(r"center\s*=\s*true", text) and re.search(r"float\s*=\s*true", text):
        return "center"
    if re.search(r"float\s*=\s*true", text):
        return "float"
    if re.search(r"float\s*=\s*false", text):
        return "tiled"
    return None


def parse_window_rules(text: str) -> dict[str, str]:
    found: dict[str, str] = {}
    for match in WINDOW_CALL.finditer(text):
        wm_class = next((group for group in match.groups() if group), "")
        if not wm_class:
            continue
        rest = text[match.end() :]
        table = first_lua_table(rest)
        if not table:
            continue
        mode = infer_mode_from_props(table)
        if mode:
            found[wm_class] = mode
    return found


def configured_modes() -> dict[str, str]:
    modes: dict[str, str] = {}
    if DEFAULT_APPS.is_dir():
        for path in sorted(DEFAULT_APPS.glob("*.lua")):
            modes.update(parse_window_rules(path.read_text(errors="replace")))
    if USER_HYPR.is_dir():
        for path in sorted(USER_HYPR.glob("*.lua")):
            if path.name == "omawin-rules.lua":
                continue
            modes.update(parse_window_rules(path.read_text(errors="replace")))
    return modes


def is_steam_game(info) -> bool:
    command = (info.get_commandline() or info.get_executable() or "")
    return bool(STEAM_GAME.search(command))


def is_steam_client(info) -> bool:
    name = (info.get_name() or "").strip().lower()
    app_id = (info.get_id() or "").strip().lower()
    return name == "steam" or app_id in STEAM_CLIENT_IDS


def include_app(info) -> bool:
    return bool(info.should_show() or is_steam_client(info))


def matches_query(info, wm_class: str, query: str) -> bool:
    if not query:
        return True
    name = (info.get_name() or "").lower()
    if query in name:
        return True
    if is_steam_game(info):
        return False
    app_id = (info.get_id() or "").lower()
    return query in app_id or query in (wm_class or "").lower()


def class_from_desktop(info) -> str:
    command = (info.get_commandline() or info.get_executable() or "").strip()
    steam = STEAM_GAME.search(command)
    if steam:
        appid = steam.group(1) or steam.group(2)
        return f"steam_app_{appid}" if appid else ""
    startup = ""
    if hasattr(info, "get_startup_wm_class"):
        startup = (info.get_startup_wm_class() or "").strip()
    if startup and startup.lower() != "steam":
        return startup
    desktop_id = (info.get_id() or "").lower()
    if desktop_id.startswith("steam.") or desktop_id in ("steam.desktop", "steam_steam.desktop"):
        return "steam"
    if "steam" in command.lower() and "steam://" in command.lower():
        return ""
    if startup:
        return startup
    if not command:
        return ""
    exe = command.split()[0]
    return os.path.basename(exe)


def describe_state(wm_class: str, override: str | None, configured: dict[str, str], clients: list[dict]) -> tuple[str, str]:
    live = live_mode_for_class(wm_class, clients)
    if live:
        return live, "open now"
    if override and override != "default":
        return override, "your rule"
    configured_mode = configured.get(wm_class)
    if configured_mode:
        return configured_mode, "desktop rule"
    return "tiled", "Hyprland default"
